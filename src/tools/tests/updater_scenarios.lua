local n, fails = 0, 0
local function eq(name, got, want)
  n = n + 1
  if got ~= want and not (type(want) == "string" and want:sub(1,1) == "~" and tostring(got):find(want:sub(2), 1, true)) then
    fails = fails + 1; print("FAIL " .. name .. ": got [" .. tostring(got) .. "] want [" .. tostring(want) .. "]")
  else print("ok   " .. name .. ": " .. tostring(got)) end
end
